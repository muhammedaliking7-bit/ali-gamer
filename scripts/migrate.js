require("dotenv").config();
const { Pool } = require("pg");

const migrationSql = `
-- ==============================================================================
-- NEXUS REALM - Neon PostgreSQL Database Migration
-- Authoritative, clean PostgreSQL schema preserving existing architecture
-- ==============================================================================

-- 1. Ensure required extensions
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 2. PROFILES TABLE
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email TEXT UNIQUE,
  gamertag TEXT NOT NULL UNIQUE,
  display_name TEXT,
  avatar_url TEXT DEFAULT 'https://images.unsplash.com/photo-1566492031773-4f4e44671857?auto=format&fit=crop&w=200&q=80',
  bio TEXT DEFAULT 'Operative enlisted in the Nexus Realm.',
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),

  CONSTRAINT gamertag_format_check CHECK (
    char_length(gamertag) >= 3 AND
    char_length(gamertag) <= 24 AND
    gamertag ~ '^[a-zA-Z0-9_]+$'
  )
);

CREATE INDEX IF NOT EXISTS profiles_gamertag_idx ON public.profiles (gamertag);

-- 3. USER FAVORITES TABLE (Wishlist)
CREATE TABLE IF NOT EXISTS public.user_favorites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  game_id TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  UNIQUE(user_id, game_id)
);

CREATE INDEX IF NOT EXISTS user_favorites_user_id_idx ON public.user_favorites (user_id);

-- 4. TOURNAMENT REGISTRATIONS TABLE
CREATE TABLE IF NOT EXISTS public.user_tournament_registrations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  tournament_id TEXT NOT NULL,
  squad_name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  UNIQUE(user_id, tournament_id)
);

CREATE INDEX IF NOT EXISTS user_tournament_reg_user_id_idx ON public.user_tournament_registrations (user_id);

-- 5. GAME REVIEWS TABLE
CREATE TABLE IF NOT EXISTS public.game_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id TEXT NOT NULL,
  author_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  author_name TEXT NOT NULL,
  author_avatar TEXT,
  rating NUMERIC(2,1) NOT NULL,
  content TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS game_reviews_game_id_idx ON public.game_reviews (game_id);

-- 6. CONTACT MESSAGES / TICKETS TABLE
CREATE TABLE IF NOT EXISTS public.contact_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  category TEXT DEFAULT 'general',
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 7. AUTO-UPDATE UPDATED_AT TRIGGER FUNCTION
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = timezone('utc'::text, now());
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_profile_updated ON public.profiles;

CREATE TRIGGER on_profile_updated
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_updated_at();
`;

async function runMigration() {
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) {
    console.error("ERROR: DATABASE_URL not found.");
    process.exit(1);
  }

  const pool = new Pool({
    connectionString,
    ssl: { rejectUnauthorized: false }
  });

  try {
    const client = await pool.connect();
    console.log("Applying Neon PostgreSQL schema migration...");
    await client.query(migrationSql);
    console.log("Migration executed successfully!");

    // Verify tables
    const res = await client.query(`
      SELECT table_name 
      FROM information_schema.tables 
      WHERE table_schema = 'public' 
      ORDER BY table_name;
    `);

    console.log("\nVerified tables in Neon database:");
    res.rows.forEach(r => console.log(` - public.${r.table_name}`));

    // Verify columns of profiles
    const profCols = await client.query(`
      SELECT column_name, data_type, is_nullable 
      FROM information_schema.columns 
      WHERE table_schema = 'public' AND table_name = 'profiles'
      ORDER BY ordinal_position;
    `);
    console.log("\nProfiles table schema:");
    profCols.rows.forEach(c => console.log(` - ${c.column_name}: ${c.data_type} (nullable: ${c.is_nullable})`));

    client.release();
    await pool.end();
    console.log("\nSchema verification PASSED.");
    process.exit(0);
  } catch (err) {
    console.error("Migration failed:", err);
    await pool.end();
    process.exit(1);
  }
}

runMigration();
