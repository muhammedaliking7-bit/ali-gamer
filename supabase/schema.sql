-- 1. PROFILES TABLE
-- Linked directly to Supabase auth.users(id) via UUID foreign key with CASCADE delete.
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  gamertag TEXT NOT NULL UNIQUE,
  display_name TEXT,
  avatar_url TEXT DEFAULT 'https://images.unsplash.com/photo-1566492031773-4f4e44671857?auto=format&fit=crop&w=200&q=80',
  bio TEXT DEFAULT 'Operative enlisted in the Nexus Realm.',
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),

  -- Ensure gamertag follows standard gaming conventions (3 to 24 chars, alphanumeric + underscores)
  CONSTRAINT gamertag_format_check CHECK (
    char_length(gamertag) >= 3 AND
    char_length(gamertag) <= 24 AND
    gamertag ~ '^[a-zA-Z0-9_]+$'
  )
);

-- Index for fast gamertag lookups
CREATE INDEX IF NOT EXISTS profiles_gamertag_idx ON public.profiles (gamertag);

-- 2. USER WISHLISTS TABLE
-- Stores saved titles per authenticated user
CREATE TABLE IF NOT EXISTS public.user_favorites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  game_id TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  UNIQUE(user_id, game_id)
);

CREATE INDEX IF NOT EXISTS user_favorites_user_id_idx ON public.user_favorites (user_id);

-- 3. TOURNAMENT REGISTRATIONS TABLE
-- Stores official tournament entries per authenticated squad captain
CREATE TABLE IF NOT EXISTS public.user_tournament_registrations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  tournament_id TEXT NOT NULL,
  squad_name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  UNIQUE(user_id, tournament_id)
);

CREATE INDEX IF NOT EXISTS user_tournament_reg_user_id_idx ON public.user_tournament_registrations (user_id);


-- ==============================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- Strict backend authorization enforcement so users cannot access or mutate
-- another operative's private credentials or data.
-- ==============================================================================

-- Enable RLS
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_favorites ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_tournament_registrations ENABLE ROW LEVEL SECURITY;

-- PROFILES POLICIES
-- Policy: Anyone (authenticated or guest) can read public operative profiles
CREATE POLICY "Public profiles are viewable by all operatives"
  ON public.profiles
  FOR SELECT
  USING (true);

-- Policy: Authenticated users can insert their own profile
CREATE POLICY "Operatives can insert their own profile"
  ON public.profiles
  FOR INSERT
  WITH CHECK (auth.uid() = id);

-- Policy: Authenticated users can update ONLY their own profile
CREATE POLICY "Operatives can update their own profile"
  ON public.profiles
  FOR UPDATE
  USING (auth.uid() = id)
  WITH CHECK (auth.uid() = id);

-- USER FAVORITES POLICIES
CREATE POLICY "Operatives can view their own wishlist"
  ON public.user_favorites
  FOR SELECT
  USING (auth.uid() = user_id);

CREATE POLICY "Operatives can insert into their own wishlist"
  ON public.user_favorites
  FOR INSERT
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Operatives can delete from their own wishlist"
  ON public.user_favorites
  FOR DELETE
  USING (auth.uid() = user_id);

-- TOURNAMENT REGISTRATIONS POLICIES
CREATE POLICY "Operatives can view their own tournament registrations"
  ON public.user_tournament_registrations
  FOR SELECT
  USING (auth.uid() = user_id);

CREATE POLICY "Operatives can register for tournaments"
  ON public.user_tournament_registrations
  FOR INSERT
  WITH CHECK (auth.uid() = user_id);


-- ==============================================================================
-- AUTOMATIC PROFILE CREATION TRIGGER
-- Securely triggers on auth.users insert to ensure every registered operative
-- immediately receives a profile row with their chosen Gamertag from metadata.
-- ==============================================================================

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  extracted_gamertag TEXT;
  clean_gamertag TEXT;
BEGIN
  -- Extract gamertag from user metadata passed during signUp
  extracted_gamertag := NEW.raw_user_meta_data->>'gamertag';

  -- If empty or missing, derive from email or generate unique fallback
  IF extracted_gamertag IS NULL OR length(trim(extracted_gamertag)) < 3 THEN
    clean_gamertag := 'Operative_' || substr(NEW.id::text, 1, 8);
  ELSE
    -- Sanitize: keep only alphanumeric and underscore characters, truncate to 24 chars
    clean_gamertag := regexp_replace(extracted_gamertag, '[^a-zA-Z0-9_]', '', 'g');
    IF length(clean_gamertag) < 3 THEN
      clean_gamertag := 'Operative_' || substr(NEW.id::text, 1, 8);
    ELSE
      clean_gamertag := substr(clean_gamertag, 1, 24);
    END IF;
  END IF;

  -- Ensure uniqueness in case of collision
  IF EXISTS (SELECT 1 FROM public.profiles WHERE gamertag = clean_gamertag) THEN
    clean_gamertag := substr(clean_gamertag, 1, 15) || '_' || substr(NEW.id::text, 1, 6);
  END IF;

  -- Insert profile record
  INSERT INTO public.profiles (
    id,
    gamertag,
    display_name,
    avatar_url,
    bio,
    created_at,
    updated_at
  ) VALUES (
    NEW.id,
    clean_gamertag,
    COALESCE(NEW.raw_user_meta_data->>'full_name', clean_gamertag),
    COALESCE(
      NEW.raw_user_meta_data->>'avatar_url',
      'https://images.unsplash.com/photo-1566492031773-4f4e44671857?auto=format&fit=crop&w=200&q=80'
    ),
    'Tactical operative enlisted in the Nexus Realm.',
    timezone('utc'::text, now()),
    timezone('utc'::text, now())
  )
  ON CONFLICT (id) DO NOTHING;

  RETURN NEW;
END;
$$;

-- Drop existing trigger if it exists
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;

-- Bind trigger to auth.users table
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_new_user();


-- ==============================================================================
-- TIMESTAMP AUTO-UPDATE TRIGGER FOR PROFILES
-- ==============================================================================

CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = timezone('utc'::text, now());
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_profile_updated ON public.profiles;

CREATE TRIGGER on_profile_updated
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_updated_at();
